import org.junit.Test

/**
 * AUDIT DB-03 (2026-11-12) — first half: the migration *registry* is now tested.
 *
 * Why not full `MigrationTestHelper` runs yet: the helper needs a schema JSON for each historical
 * version generated by the Room compiler. `exportSchema` had always been `false`, so those files
 * have never existed for versions 1..13 and cannot be back-filled (they describe what the code
 * looked like at each past release). They will accumulate from version 14 onward now that export
 * is on, at which point this test grows into real per-boundary execution tests.
 *
 * What can be proven today, and is worth proving: every version between 1 and 14 is covered by
 * exactly one migration, with no gap and no duplicate. A gap means Room throws at open time on
 * any device sitting on the missing version; a duplicate means one of the two is never used.
 * Neither would be caught by any existing test.
 */
class MigrationRegistryTest {

    /** The current `@Database(version = ...)`. */
    private val currentVersion = 14

    private val allMigrations = listOf(
        MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5, MIGRATION_5_6,
        MIGRATION_6_7, MIGRATION_7_8, MIGRATION_8_9, MIGRATION_9_10, MIGRATION_10_11,
        MIGRATION_11_12, MIGRATION_12_13, MIGRATION_13_14
    )

    @Test
    fun `every version path from 1 to the current version is covered`() {
        val covered = allMigrations.map { it.startVersion to it.endVersion }.toSet()
        val expected = (1 until currentVersion).map { it to (it + 1) }.toSet()
        assertEquals(
            "AUDIT DB-03: a missing step here is a device that cannot open its database after " +
                "updating - Room has no path from its stored version to the current one.",
            expected,
            covered
        )
    }

    @Test
    fun `no migration starts from a version that is already behind another step`() {
        val starts = allMigrations.map { it.startVersion }
        assertEquals(
            "two migrations from the same version means one of them is dead code and nobody " +
                "can tell which one runs",
            starts.size,
            starts.toSet().size
        )
    }

    @Test
    fun `no migration targets a version above the database version`() {
        assertTrue(
            "AUDIT DB-03: a migration ending past @Database(version) would never run, and its " +
                "existence hides that the schema change was never wired up",
            allMigrations.all { it.endVersion <= currentVersion }
        )
    }

    @Test
    fun `the chain is contiguous - each step begins where the previous one ended`() {
        val ordered = allMigrations.sortedBy { it.startVersion }
        ordered.forEachIndexed { index, migration ->
            assertEquals(
                "step ${index + 1} must begin at version ${index + 1}",
                index + 1,
                migration.startVersion
            )
            assertEquals(migration.startVersion + 1, migration.endVersion)
        }
    }

    @Test
    fun `the count of migrations matches the version span`() {
        assertEquals(
            "one migration per version step keeps the chain auditable at a glance",
            currentVersion - 1,
            allMigrations.size
        )
    }
}
